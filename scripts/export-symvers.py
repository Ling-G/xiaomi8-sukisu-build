#!/usr/bin/env python3
"""Export the kernel-only symbol table and verify it against this vmlinux."""
import argparse
import hashlib
import json
import shutil
import subprocess
from pathlib import Path


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def export(out, artifacts, nm):
    source = out / "Module.symvers"
    rows = {}
    for line in source.read_text().splitlines():
        fields = line.split()
        if len(fields) != 4 or fields[2] != "vmlinux":
            raise ValueError(f"Expected kernel-only modpost output: {line}")
        crc, name, _, export_type = fields
        if name in rows or not export_type.startswith("EXPORT_"):
            raise ValueError(f"Unexpected or duplicate export: {line}")
        rows[name] = int(crc, 16)
    if not rows or not rows.get("module_layout"):
        raise ValueError("Missing nonzero module_layout CRC")

    symbols = subprocess.check_output([nm, "--defined-only", str(out / "vmlinux")], text=True)
    actual = {}
    for line in symbols.splitlines():
        fields = line.split()
        if len(fields) == 3 and fields[2].startswith("__crc_"):
            if fields[1] != "A":
                raise ValueError(f"Expected absolute CRC symbol: {line}")
            actual[fields[2][6:]] = int(fields[0], 16) & 0xffffffff
    if actual != rows:
        missing = sorted(rows.keys() - actual.keys())
        extra = sorted(actual.keys() - rows.keys())
        mismatch = sorted(n for n in rows.keys() & actual.keys() if rows[n] != actual[n])
        raise ValueError(f"vmlinux CRC mismatch: missing={missing[:10]}, extra={extra[:10]}, changed={mismatch[:10]}")

    shutil.copyfile(source, artifacts / "Module.symvers")
    (artifacts / "kernel-export-crcs.txt").write_text(
        "".join(f"0x{actual[n]:08x}\t{n}\n" for n in sorted(actual)), encoding="utf-8")
    report = {
        "passed": True,
        "scope": "Exports of built-in vmlinux only; no external module exports",
        "source": "out/Module.symvers generated by kernel modpost",
        "verification": "Every entry matches the absolute __crc_* symbol in the same vmlinux",
        "exported_symbols": len(rows),
        "module_layout_crc": f"0x{rows['module_layout']:08x}",
        "image_gzip_sha256": sha256(artifacts / "Image.gz"),
        "kernel_config_sha256": sha256(artifacts / "kernel.config"),
        "module_symvers_sha256": sha256(artifacts / "Module.symvers"),
    }
    (artifacts / "symvers-check.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("out", type=Path)
    p.add_argument("artifacts", type=Path)
    p.add_argument("nm")
    a = p.parse_args()
    export(a.out, a.artifacts, a.nm)
